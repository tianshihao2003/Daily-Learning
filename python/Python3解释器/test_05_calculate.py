# ============================================
# 题目5：使用交互式模式进行计算
# ============================================
# 在交互式环境中完成以下计算：
# 1. 计算 100 / 3（保留小数）
# 2. 计算 100 // 3（整除）
# 3. 计算 2 ** 10（乘方）
# 4. 用 type() 查看结果类型
# ============================================

# 直接运行本文件查看效果：
print("100 / 3 =", 100 / 3)
print("type:", type(100 / 3))

print("\n100 // 3 =", 100 // 3)
print("type:", type(100 // 3))

print("\n2 ** 10 =", 2 ** 10)
print("type:", type(2 ** 10))
