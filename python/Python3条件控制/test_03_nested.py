# 完成以下操作：
# 1. 输入一个整数 num
# -> num = int(input("提示语"))
# 2. 先判断是否为偶数（num % 2 == 0）
# -> if num % 2 == 0:
# 3. 如果是偶数，再判断是否能被 3 整除
# -> if num % 3 == 0:
# 4. 如果是奇数，再判断是否能被 3 整除
# -> else: if num % 3 == 0:
# ============================================

# 在下面写你的代码：
num = int(input("请输入："))

if num % 2 == 0:
    if num % 3 == 0:
        print("是整数，而且能被三整除")
    else:
        print("是整数，不能被三整除")
else:
    if num % 3 == 0:
        print("是奇数，能被3整除")
    else:
        print("是奇数，不能被3整除")


