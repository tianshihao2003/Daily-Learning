# 完成以下操作：
# 1. 创建列表 a = [1, 2, 3, 4, 5]
# -> 变量赋值
# 2. 用 del 删除索引 2 的元素
# -> del list[索引]
# 3. 用 remove() 删除值为 4 的元素
# -> list.remove(值)
# 4. 用 pop() 删除最后一个元素
# -> list.pop()
# 5. 打印每次操作后的列表
# -> print(list)
# ============================================

# 在下面写你的代码：
a = [1, 2, 3, 4, 5]

del a[2]
print(a)
a.remove(4)
print(a)
a.pop()
print(a)


