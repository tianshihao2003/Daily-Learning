# 完成以下操作：
# 1. 输入一个数字 day（1-7）
# 2. 用 match...case 判断是星期几
# 3. 1-7 分别对应"星期一"到"星期日"
# ============================================

# 在下面写你的代码：
day = int(input("今天周几？"))

match day:
    case 1:
        print("星期一")
    case 2:
        print("星期二")
    case 3:
        print("星期三")
    case 4:
        print("星期四")
    case 5:
        print("星期五")
    case 6:
        print("星期六")
    case 7:
        print("星期日")
    case _:
        print("输入无效")


