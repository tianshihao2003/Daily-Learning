# 在下面写你的代码：
score = int(input("请输入你的成绩："))
if 90 <= score <= 100:
    print("优秀")
elif score >= 80:
    print("良好")
elif score >= 70:
    print("中等")
elif score >= 60:
    print("及格")
else:
    print("不及格")


