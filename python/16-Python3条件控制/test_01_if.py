# 完成以下操作：
# 1. 输入一个整数 num
# 2. 如果 num > 0，打印"正数"
# 3. 如果 num == 0，打印"零"
# 4. 如果 num < 0，打印"负数"
# ============================================

# 在下面写你的代码：
num = int(input("请输入："))

if num > 0:
    print("正数")
elif num == 0:
    print("零")
else:
    print("负数")


