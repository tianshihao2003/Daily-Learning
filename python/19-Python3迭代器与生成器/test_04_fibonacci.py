# 完成以下操作：
# 1. 用 yield 实现斐波那契数列生成器 |---知识点：yield a 返回当前值---|
# ============================================
# 说明：
# - 斐波那契数列：0, 1, 1, 2, 3, 5, 8, 13...（每个数是前两个数之和）
# - a, b = b, a + b 是同时赋值：先计算右边，再同时赋给左边
# ============================================
# 在下面写你的代码：
def fib():
    a,b=0,1
    while True:
        yield a
        a,b=b,a+b

fi=fib()
for i in range(20):
    print(next(fi))



