# 完成以下操作：
# 1. 用 yield 创建一个生成器，生成 1-10 的平方数
# ============================================
# 说明：
# - yield 关键字：暂停函数执行，返回一个值，下次调用时从暂停处继续
# - 生成器函数：包含 yield 的函数，调用后返回一个生成器对象
# - 可以用 next() 或 for 循环逐步获取值
# ============================================

# 在下面写你的代码：
def squares(n):
    for i in range(1, n + 1):
        yield i**2


gen = squares(10)
print(next(gen))
print(next(gen))

for i in gen:
    print(i, end=" ")


