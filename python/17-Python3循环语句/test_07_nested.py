# 完成以下操作：
# 1. 用嵌套 for 循环打印乘法表（1-5） |---知识点：for i in range(1, 6):---|
# 2. 输出格式：1x1=1、1x2=2...5x5=25 |---知识点：for j in range(1, 6): print(f"{i}x{j}={i*j}")---|
