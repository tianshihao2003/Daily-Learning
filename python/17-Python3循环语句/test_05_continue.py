# ============================================
# 完成以下操作：
# 1. 用 for 循环打印 1 到 10 |---知识点：for i in range(1, 11):---|
# 2. 如果数字是 5，用 continue 跳过不打印 |---知识点：if i == 5: continue---|
# ============================================
# 在下面写你的代码：
for i in range(1, 11):
    if i == 5:
        continue
    print(i, end=" ")


