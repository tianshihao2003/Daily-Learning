# ============================================
# 题目2-6：for...else 语句
# ============================================
# 完成以下操作：
# 1. 在列表 [1, 3, 5, 7, 9] 中查找数字 6
# 2. 如果找到，打印"找到了"
# 3. 如果没找到（循环正常结束），打印"没找到"
# ============================================

# 在下面写你的代码：
nums = [1, 3, 5, 7, 9]
for i in nums:
    if i == 6:
        print("找到了")
        break
    else:
        if i == nums[-1]:
            print("没找到")
