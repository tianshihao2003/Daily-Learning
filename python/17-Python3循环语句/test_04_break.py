# 题目2-4：break 跳出循环
# ============================================
# 完成以下操作：
# 1. 用 while 循环，从 1 开始累加
# 2. 当总和超过 100 时，用 break 跳出循环
# 3. 打印最后加的数字和总和
# ============================================

# 在下面写你的代码：
i = 1
z = 1
while True:
    i += 1
    z += i
    if z > 100:
        break
print(z)


