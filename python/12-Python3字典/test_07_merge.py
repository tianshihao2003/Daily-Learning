# 题目2-7：字典合并与复制
# ============================================
# 完成以下操作：
# 1. 创建字典 d1 = {"a": 1, "b": 2} 和 d2 = {"c": 3, "d": 4}
# 2. 把 d2 的键值对合并到 d1 里去
# 3. 复制一份 d1 给 d3（要独立副本，改 d1 不能影响 d3）
# 4. 修改 d1 的 "a" 为 10，观察 d3 是否变化
# ============================================

# 在下面写你的代码：
d1 = {"a": 1, "b": 2}
d2 = {"c": 3, "d": 4}

d1.update(d2)
d3 = d1.copy()
d1["a"] = 10
print(d1)
print(d3)


