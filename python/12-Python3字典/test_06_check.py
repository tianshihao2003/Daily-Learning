# 完成以下操作：
# 1. 创建字典 d = {"apple": 5, "banana": 3, "orange": 8}
# -> {key: value, key: value}
# 2. 用 in 判断 "apple" 是否在字典中
# -> key in dict
# 3. 用 len() 统计字典长度
# -> len(dict)
# 4. 用 get() 获取 "grape" 的数量（不存在返回 0）
# -> dict.get(key, 默认值)
# ============================================

# 在下面写你的代码：
d = {"apple": 5, "banana": 3, "orange": 8}

print("apple" in d)
print(len(d))
print(d.get("grape", 0))


