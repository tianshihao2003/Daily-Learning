# 题目3：range() 函数
# ============================================
# 完成以下操作：
# 1. 用 range(1, 11) 打印 1 到 10 |---知识点：range(开始, 结束)---|
# 2. 用 range(0, 10, 2) 打印 0 到 10 的偶数 |---知识点：range(开始, 结束, 步长)---|
# 3. 用 range(10, 0, -1) 倒序打印 10 到 1 |---知识点：range(开始, 结束, 负步长)---|
# ============================================
# 在下面写你的代码：
for i in range(1,11):
    print(i)
for i in range(0,11,2):
    print(i)
for i in range(10,0,-1):
    print(i)

