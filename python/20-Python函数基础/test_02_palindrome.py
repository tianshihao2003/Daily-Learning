# ============================================
# 定义一个函数 is_palindrome(s)，判断字符串是否是回文串
# 1. 回文串：正读和反读相同
# 2. 字符串切片 s[::-1] 可以反转字符串
# ============================================

# 在下面写你的代码：
def is_palindrome(s):
    return s == s[::-1]


print(is_palindrome("level"))


