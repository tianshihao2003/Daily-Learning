# 题目2-3：时间转换
# ============================================
# 定义一个函数 time_convert(seconds)，将秒转换为小时、分钟、秒
# 1. 小时 = 秒 // 3600
# 2. 分钟 = (秒 % 3600) // 60
# 3. 剩余秒 = (秒 % 3600) % 60
# ============================================

# 在下面写你的代码：
def time_conver(seconds):
    hours=seconds//3600
    minutes=seconds%3600//60
    seconds=seconds%3600%60
    return f"{hours} 小时 {minutes} 分钟 {seconds} 秒"

print(time_conver(772))



