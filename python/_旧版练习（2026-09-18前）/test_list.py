fruits = ["苹果","香蕉","橘子","葡萄"]

print(f"第一个元素：{fruits[0]}")
print(f"最后一个元素：{fruits[-1]}")
print(f"索引 1 到 3 的切片：{fruits[1:3]}")
print(f"拼接另一个列表：{fruits + ['西瓜']}")
