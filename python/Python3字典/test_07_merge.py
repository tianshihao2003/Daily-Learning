# 题目7：字典合并与复制
# ============================================
# 完成以下操作：
# 1. 创建字典 d1 = {"a": 1, "b": 2} 和 d2 = {"c": 3, "d": 4}
# -> {key: value, key: value}
# 2. 用 update() 将 d2 合并到 d1
# -> dict1.update(dict2)
# 3. 用 copy() 复制 d1 到 d3
# -> dict.copy()
# 4. 修改 d1 的 "a" 为 10，观察 d3 是否变化
# -> dict[key] = value
# ============================================

# 在下面写你的代码：
d1 = {"a": 1, "b": 2}
d2 = {"c": 3, "d": 4}

d1.update(d2)
d3 = d1.copy()
d1["a"] = 10
print(d1)
print(d3)


