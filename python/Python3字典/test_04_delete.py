# 完成以下操作：
# 1. 创建字典 d = {"a": 1, "b": 2, "c": 3, "d": 4}
# -> {key: value, key: value}
# 2. 用 del 删除键 "a"
# -> del dict[key]
# 3. 用 pop() 删除键 "b"，并获取其值
# -> dict.pop(key)
