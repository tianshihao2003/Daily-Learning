# 题目2-2：给函数加类型注解（单返回值）
# ============================================
# 完成以下操作：
# 1. 写函数 average(scores)：参数是整数列表，返回值是小数
# 2. 参数和返回值都加上类型注解
# 3. 用 [85, 90, 95, 100] 调用并打印结果（应该是 92.5）
# ============================================

# 在下面写你的代码：
def average(scores: list[int]) -> float:
    return sum(scores) / len(scores)

print(average([85, 90, 95, 100]))




