# 完成以下操作：
# 1. 创建集合 a = {1, 2, 3, 4} 和 b = {3, 4, 5, 6}
# 2. 计算交集（两个集合都有的元素）
# 3. 计算并集（两个集合合起来的所有元素）
# 4. 计算差集（在 a 里但不在 b 里的元素）
# 5. 计算对称差集（只出现在其中一个集合里的元素）
