# 完成以下操作：
# 1. 用集合推导式生成 1-10 中所有偶数的集合
# 2. 用集合推导式从字符串 "abracadabra" 中去除 a、b、c
# ============================================

# 在下面写你的代码：
s = {x for x in range(1, 11) if x % 2 == 0}
print(s)

b = {x for x in "abracadabra" if x not in "abc"}
print(b)


