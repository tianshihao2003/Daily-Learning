# ============================================
# 完成以下操作：
# 1. 创建集合 a = {1, 2, 3, 4} 和 b = {3, 4, 5, 6}
# -> {元素1, 元素2, ...}
# 2. 计算交集（& 或 intersection()）
# -> set1 & set2
# 3. 计算并集（| 或 union()）
# -> set1 | set2
# 4. 计算差集（- 或 difference()）
# -> set1 - set2
# 5. 计算对称差集（^ 或 symmetric_difference()）
# -> set1 ^ set2
# ============================================

# 在下面写你的代码：
a = {1, 2, 3, 4}
b = {3, 4, 5, 6}

print(a & b)
print(a | b)
print(a - b)
print(a ^ b)


